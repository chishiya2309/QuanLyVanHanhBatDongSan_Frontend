import { act, renderHook, waitFor } from '@testing-library/react';
import { describe, expect, it, vi } from 'vitest';
import { useProfile } from '../src/hooks/useProfile';
import { profileMessages as m } from '../src/types/profile';
import { adminProfile, customerProfile, hostProfile } from './fixtures/profiles';
import { deferred, failure, installApi, ok } from './apiMock';

describe('profile state', () => {
  it('keeps the draft after a failure, rejects double submission and updates from the server on retry', async () => {
    const api = installApi(adminProfile);
    const expired = vi.fn();
    const { result } = renderHook(() => useProfile(expired));
    await waitFor(() => expect(result.current.profile).toEqual(adminProfile));
    act(() => result.current.startEditing());
    act(() => result.current.handleFieldChange('fullName', 'Admin mới'));
    const gate = deferred<Response>();
    api.patchProfile.mockReturnValueOnce(gate.promise);
    let pending!: Promise<void>;
    act(() => { pending = result.current.handleSubmit(); void result.current.handleSubmit(); });
    await waitFor(() => expect(api.patchProfile).toHaveBeenCalledTimes(1));
    await act(async () => { gate.resolve(failure(500, m.saveFailure)); await pending; });
    expect(result.current.formData).toMatchObject({ fullName: 'Admin mới' });
    expect(result.current.isEditing).toBe(true);
    expect(result.current.generalErrorMessage).toBe(m.saveFailure);
    api.patchProfile.mockResolvedValueOnce(ok({ ...adminProfile, fullName: 'Admin mới' }));
    await act(async () => { await result.current.handleSubmit(); });
    expect(result.current.profile).toMatchObject({ fullName: 'Admin mới' });
    expect(result.current.isEditing).toBe(false);
    expect(result.current.successMessage).toBe(m.success);
  });
  it('never permits Customer editing or PATCH', async () => {
    const api = installApi(customerProfile);
    const expired = vi.fn();
    const { result } = renderHook(() => useProfile(expired));
    await waitFor(() => expect(result.current.profile?.role).toBe('CUSTOMER'));
    act(() => result.current.startEditing());
    await act(async () => { await result.current.handleSubmit(); });
    expect(result.current.isEditing).toBe(false);
    expect(api.patchProfile).not.toHaveBeenCalled();
  });
  it('replaces, removes, undoes and revokes logo previews, restoring the original draft on cancel', async () => {
    installApi({ ...hostProfile, logoUrl: '/original.png' });
    const expired = vi.fn();
    const { result, unmount } = renderHook(() => useProfile(expired));
    await waitFor(() => expect(result.current.profile?.role).toBe('HOST'));
    act(() => result.current.startEditing());
    const file = new File(['png'], 'new.png', { type: 'image/png' });
    act(() => result.current.handleLogoSelect(file));
    const first = result.current.logoPreviewUrl;
    act(() => result.current.handleLogoSelect(file));
    expect(URL.revokeObjectURL).toHaveBeenCalledWith(first);
    const second = result.current.logoPreviewUrl;
    act(() => result.current.handleRemoveLogoToggle());
    expect(URL.revokeObjectURL).toHaveBeenCalledWith(second);
    expect(result.current.logoFile).toBeNull();
    expect(result.current.removeLogo).toBe(true);
    act(() => result.current.handleRemoveLogoToggle());
    expect(result.current.isDirty).toBe(false);
    act(() => { result.current.handleFieldChange('businessName', 'Draft'); result.current.handleLogoSelect(file); });
    const cancelled = result.current.logoPreviewUrl;
    act(() => result.current.cancelEditing());
    expect(URL.revokeObjectURL).toHaveBeenCalledWith(cancelled);
    expect(result.current.formData).toMatchObject({ businessName: hostProfile.businessName });
    act(() => result.current.startEditing());
    act(() => result.current.handleLogoSelect(file));
    const final = result.current.logoPreviewUrl;
    unmount();
    expect(URL.revokeObjectURL).toHaveBeenCalledWith(final);
  });
  it('blocks an invalid selected image until corrected and clears removal on a valid selection', async () => {
    const api = installApi(hostProfile);
    const expired = vi.fn();
    const { result } = renderHook(() => useProfile(expired));
    await waitFor(() => expect(result.current.profile).toEqual(hostProfile));
    act(() => result.current.startEditing());
    act(() => result.current.handleLogoSelect(new File(['gif'], 'logo.gif', { type: 'image/gif' })));
    await act(async () => { await result.current.handleSubmit(); });
    expect(result.current.fieldErrors.logo).toBe(m.imageFailure);
    expect(api.patchProfile).not.toHaveBeenCalled();
    act(() => result.current.handleRemoveLogoToggle());
    act(() => result.current.handleLogoSelect(new File(['png'], 'logo.png', { type: 'image/png' })));
    expect(result.current.removeLogo).toBe(false);
    expect(result.current.fieldErrors.logo).toBeUndefined();
  });
  it('ignores older GET responses and responses arriving after unmount', async () => {
    const api = installApi(adminProfile);
    const expired = vi.fn();
    const { result, unmount } = renderHook(() => useProfile(expired));
    await waitFor(() => expect(result.current.profile).toEqual(adminProfile));
    const old = deferred<Response>();
    api.getProfile.mockReturnValueOnce(old.promise);
    let first!: Promise<void>;
    act(() => { first = result.current.fetchProfile(); });
    api.getProfile.mockResolvedValueOnce(ok({ ...adminProfile, fullName: 'Newest' }));
    await act(async () => { await result.current.fetchProfile(); });
    await act(async () => { old.resolve(ok({ ...adminProfile, fullName: 'Old' })); await first; });
    expect(result.current.profile).toMatchObject({ fullName: 'Newest' });
    const late = deferred<Response>();
    api.getProfile.mockReturnValueOnce(late.promise);
    act(() => { first = result.current.fetchProfile(); });
    unmount();
    await act(async () => { late.resolve(failure(401, m.sessionInvalid)); await first; });
    expect(expired).not.toHaveBeenCalled();
  });
  it('maps editable errors inline and protected or unknown fields to the banner', async () => {
    const api = installApi(hostProfile);
    const expired = vi.fn();
    const { result } = renderHook(() => useProfile(expired));
    await waitFor(() => expect(result.current.profile).toEqual(hostProfile));
    act(() => result.current.startEditing());
    api.patchProfile.mockResolvedValueOnce(failure(409, m.phoneDuplicate, { phoneNumber: m.phoneDuplicate }));
    await act(async () => { await result.current.handleSubmit(); });
    expect(result.current.fieldErrors.phoneNumber).toBe(m.phoneDuplicate);
    act(() => result.current.handleFieldChange('phoneNumber', '+84901234567'));
    expect(result.current.fieldErrors.phoneNumber).toBeUndefined();
    api.patchProfile.mockResolvedValueOnce(failure(400, m.fieldProtected, { accountId: m.fieldProtected, email: m.emailProtected }));
    await act(async () => { await result.current.handleSubmit(); });
    expect(result.current.generalErrorMessage).toContain(m.fieldProtected);
    expect(result.current.generalErrorMessage).toContain(m.emailProtected);
  });
});
